-- 0145 —— 星球带上那句原话。
--
-- # 它是什么
--
-- 「它想问你」下面那个问题，模型是从正文里某一句话读出来的。这一列存的就是
-- 那一句，逐字照抄。
--
-- # 为什么要存，而不是只在生成时验一遍
--
-- 验是必须的：写这条问题的那次调用，服务端拿 evidence 回正文里查，查不到就打回
-- 去重写，再查不到就丢掉这颗星（internal/news/write.go）。所以库里的每一行都
-- 已经过了那道校验。
--
-- 存下来是为了另外两件事：
--
--  1. **给她看。** 一个问题旁边摆着它出自的那句原话，她自己就能判断这个问题
--     问得对不对 —— 这正是我们想教的那件事。
--  2. **给我们查。** 校验只保证这句话在正文里，不保证问题问得好。问题写歪的
--     那天，有这一列才看得出是模型读错了那一句，还是那一句本来就不该被拿来
--     提问。没有它，只能对着一个中文问题猜。
--
-- 允许为空：0145 之前生成的那些行没有这一列的内容，它们照常显示，只是问题旁边
-- 没有出处。

-- +goose Up
ALTER TABLE news_planet ADD COLUMN evidence text NOT NULL DEFAULT '';

COMMENT ON COLUMN news_planet.evidence IS
  '钩子出自正文的哪一句，逐字照抄（原文语言）。写入前已验过它确实出现在正文里。空串 = 0145 之前生成的旧行。';

-- 🚨 顺带把 title_zh 的说明改对。0120 建表时写的是「title_zh 是**重写过的**，
-- 不是原标题的翻译」，而那条指令正是这次要改掉的东西：它产出过
-- 「AI白天使11天？数学难题争议更大」——原标题里的每一个信息都没了。现在它是
-- 原标题的如实翻译，界面上和 title_en 并排显示。
COMMENT ON COLUMN news_planet.title_zh IS
  '原标题的如实翻译（不是改写）。校验见 internal/news/write.go 的 checkTitle：原标题不是问句时译文里不许有问号，也不许出现原标题里没有的数字。';

