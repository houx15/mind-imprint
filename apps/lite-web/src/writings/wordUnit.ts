/**
 * 这一篇的篇幅按「字」数还是按「词」数说。
 *
 * 🚨 数数那件事本来就是对的 —— `countWords`（pro 那份，CJK-aware）中文一个字
 * 算一个、英文一个词算一个，和服务端 `agent.CountWords` 是同一套。**错的是
 * 单位那个字。** 段落和成稿两处都把它写死成「字」，于是一篇英文稿子上显示的是
 *「已保存 · 167 字」。
 *
 * 这正是 wordcount.ts 开头那段注释警告过的同一类事故（2026-08-25 BUG-02：
 * 一篇 165 词的英文稿显示「986 字」，让一个目标 800 词的作者以为自己超了）。
 * 那一次修的是数错，这一次修的是说错 —— 数对了、单位写错，她一样没法判断
 * 自己到没到。
 *
 * 2026-09-12 第十二轮线上走查，英文那个学生连着四步在算自己超没超：
 *   「上面显示已写136词，但我之前跟印记说是163词，我不知道现在到底超没超」
 *   「上面显示已写200词，但老师只要150左右，我得先删掉一些」
 *
 * 设定弹窗里本来就是分语言写的（`lang === "en" ? "words" : "字"`），
 * 只有房间里这几处没跟上。
 */
export function wordUnit(lang: string | null | undefined): string {
  return lang === "en" ? "词" : "字";
}
