/**
 * 一段里的几步 —— 段落那一步的引导框顶上那一节。
 *
 * # 为什么是这个（同事 2026-09-20 的意见 5）
 *
 *	「到了分段写作的界面，需要组织的内容为**一个段落内的文本结构**。
 *	  ……写作引导：语言还是有点笨，几种写法不太规范，我找了一些论证结构的
 *	  思维导图和教辅，可以参考一下这些论证方法规范一下语言。」
 *
 * 引导框原来那一节叫「常见的几种写法」，摆的是几个**方法名**（举个例子、
 * 比一比……）。但她站在一段空白面前要的不是「有哪几种写法」，是
 * **这一段先写什么、再写什么**。方法名回答的是另一个问题。
 *
 * # R4（2026-09-21）：换成讲义的五句型
 *
 * 依据从「那页教辅的分析段内层次」换成了产品负责人拿来的那位语文老师的
 * `docs/reference/writing-teaching/议论文写作汇总（五）讲义.md`。
 * 主体段原来是四步（分论点句 / 论据 / 分析 / 回扣），讲义是五句：
 *
 *	观点句 → 阐释句 → 材料句 → 分析句 → 结论句
 *
 * 少的那一句是**阐释句**，而它恰好是学生最常跳过的一句：观点句写完直接跳到
 * 例子，抽象的主张和具体的事之间没有桥，读者得自己搭。
 *
 * 「分析」那一格也换了说法。R2 上线那天模型自己说的是「例子讲完就结束了，
 * 还差一句把它和主张连起来的话」—— 它认得出缺什么，说不出那一句叫什么。
 * 讲义给了三个名字（因果 / 假设 / 归纳），三条都在方法库里带着句式。
 *
 * 记叙文那四种（场景 / 细节 / 转折 / 感悟）是 R4 新开的，来源是另外两份讲义。
 *
 * # 🚨 这一节是确定性渲染的，不花模型调用
 *
 * 按 kind 查这张表，和卡片派生是同一个路子。模型那一份只管 `job` /
 * `method_ids` / `questions` —— 一段的骨架是固定的知识，每次让模型重说一遍
 * 既费钱又会漂（同事的意见 7：「每一次刷新就会变成新的东西」）。
 *
 * 🚨 `apps/api/internal/api/writing_sentence.go` 是它的 Go 孪生，
 * 陪练判「这一段缺哪一句」时用的是那一份。两边的步数、次序、用词必须一致。
 */
