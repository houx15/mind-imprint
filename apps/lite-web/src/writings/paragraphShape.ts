/**
 * 这一种块的段内结构。没有对应的（自由段落、论据）返回空数组 ——
 * 那时候这一节整个不渲染，而不是摆一份不适用的步骤。
 */
export function paragraphShapeOf(kind: OutlineKind | string): ParagraphStep[] {
  return SHAPES[kind] ?? [];
}
