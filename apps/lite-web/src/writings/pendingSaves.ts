/**
 * 她还没存下去的字，在问印记之前先存完。
 *
 * # 为什么需要这么一件东西
 *
 * 第三十八轮走查，十六条卡壳里十条是同一件事，两个学生各说各的：
 *
 *	「印记说我的证据句没有数字，但框[0]里明明已经写了 14 plates」
 *	「框里明明已经有让步的句子了，印记还说我缺让步，不知道是不是没刷新」
 *	「不知道是不是系统延迟还是我之前就改了没保存上」
 *
 * 最后那句她自己猜到了：**是没保存上**。陪练读的是服务端那一份，而她刚敲进
 * 框里的字还在 1.2 秒的防抖里等着 —— 她一敲完就问印记，这一轮上文里就没有
 * 那句话。印记于是照着一份少了那句话的正文说「你缺 X」，而她盯着屏幕上明明
 * 写着的 X。
 *
 * 这和「陪练读段落不读成稿」「横幅只说总评」是同一族的第三处：
 * **屏幕上有两份她的文字，而说话的那一方读的不是她眼前那一份。**
 * 前两处是读错了地方，这一处是读得太早。
 *
 * # 为什么是一个模块级的登记处，而不是把回调一层层传下去
 *
 * 待存的字在每一块 `BlockCard` 自己的 state 里；`say()` 在
 * `WritingRoomHost` 里，中间隔着 `StagePanel` 和 `SnippetsStage`。要把它接上，
 * 要么把一个 ref 穿过三层组件，要么在这里放一个登记处。
 *
 * 选后者，因为这件事天然是**单例**的：一个写作房间在同一时刻只挂一个。
 * 代价写明白：这份状态在模块作用域里，测试之间不会自动清空 —— 所以
 * `registerPendingSave` 返回注销函数，组件卸载时必须调用它。
 */

type Flush = () => Promise<void>;

const pending = new Set<Flush>();

/**
 * 登记一个「把这一块还没存的字存下去」的动作。
 *
 * 返回注销函数。组件卸载时一定要调用 —— 不然一个已经不在屏幕上的块会一直
 * 留在这里，下一次 flush 会去存一份早就没人看的文字。
 */
export function registerPendingSave(flush: Flush): () => void {
  pending.add(flush);
  return () => {
    pending.delete(flush);
  };
}

/**
 * 把登记在册的都存完再往下走。
 *
 * 🚨 单个失败不阻断其余的：一块存不上不该让她连话都发不出去。
 * 存失败的那一块自己会把错误显示在它自己的位置上。
 */
export async function flushPendingSaves(): Promise<void> {
  if (pending.size === 0) return;
  await Promise.all([...pending].map((f) => f().catch(() => undefined)));
}
